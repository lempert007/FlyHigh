def _poi_page_body(pdf: MissionPDF, data: LastPlanData) -> None:
    """POI detail cards (one per POI, auto-paginate)."""
    if not data.pois:
        return

    pdf.header_bar("POINT-OF-INTEREST DETAILS")
    pdf.section_title("POI Maneuver Plans")

    for j, poi in enumerate(data.pois):
        m = poi.maneuver
        name = poi.name or f"POI {j + 1}"
        agl_min = m.poi_min_agl_m if m.poi_min_agl_m is not None else data.fc.min_agl_m
        agl_max = m.poi_max_agl_m if m.poi_max_agl_m is not None else data.fc.max_agl_m
        poi_dist = data.poi_distances[j] if j < len(data.poi_distances) else None
        maneuver_label = {
            ManeuverType.LAWNMOWER: "Lawnmower",
            ManeuverType.WARP_WEFT: "Warp & Weft",
            ManeuverType.SMART_LAWNMOWER: "Smart Lawnmower",
        }.get(m.type, m.type)
        poly_note = " (custom polygon)" if m.polygon else ""

        rows = [
            ("Coordinates", f"{poi.point.lat:.6f}, {poi.point.lon:.6f}"),
            ("Maneuver type", f"{maneuver_label}{poly_note}"),
            (
                "Coverage area",
                f"{m.width_m:.0f} m \u00d7 {m.height_m:.0f} m = {_fmt_area(m.width_m * m.height_m)}",
            ),
            ("Sweep spacing", f"{m.sweep_spacing_m:.1f} m"),
            ("AGL band", f"{agl_min:.0f} \u2013 {agl_max:.0f} m"),
            ("Distance on route", _fmt_dist(poi_dist) if poi_dist is not None else "\u2014"),
        ]
        card_h = len(rows) * _ROW_H + 22
        y0 = pdf.get_y()
        if y0 + card_h > _PAGE_H - 28:
            pdf.add_page()
            pdf.header_bar("POINT-OF-INTEREST DETAILS (cont.)")
            y0 = pdf.get_y()

        # Card outline
        pdf.set_fill_color(*_BG_SURFACE)
        pdf.set_draw_color(*_BORDER)
        pdf.set_line_width(0.2)
        pdf.rect(_MARGIN, y0, _CONTENT_W, card_h, style="FD")

        # Left accent (primary blue)
        pdf.set_fill_color(*_PRIMARY)
        pdf.rect(_MARGIN, y0, 3, card_h, style="F")

        # Number badge
        bx, by = _MARGIN + 6, y0 + 5
        pdf.set_fill_color(*_PRIMARY)
        pdf.ellipse(bx, by, 7, 7, style="F")
        pdf.set_font(pdf._font_family, "B", 9)
        pdf.set_text_color(*_WHITE)
        pdf.set_xy(bx, by + 0.5)
        pdf.cell(7, 6, str(j + 1), align="C", ln=0)

        # POI name
        pdf.set_font(pdf._font_family, "B", 11)
        pdf.set_text_color(*_TEXT)
        pdf.set_xy(_MARGIN + 17, y0 + 6)
        pdf.cell(90, 6, name, ln=0)

        # Maneuver chip
        chip_text = maneuver_label.upper()
        pdf.set_font(pdf._font_family, "B", 6)
        chip_w = pdf.get_string_width(chip_text) + 8
        chip_x = _MARGIN + _CONTENT_W - chip_w - 5
        pdf.set_fill_color(225, 240, 255)
        pdf.set_draw_color(*_PRIMARY)
        pdf.set_line_width(0.15)
        pdf.rect(chip_x, y0 + 6, chip_w, 6, style="FD")
        pdf.set_text_color(*_PRIMARY)
        pdf.set_xy(chip_x + 3, y0 + 7)
        pdf.cell(chip_w - 6, 4, chip_text, ln=0)

        # Separator under header
        sep_y = y0 + 15
        pdf.set_draw_color(*_BORDER)
        pdf.set_line_width(0.2)
        pdf.line(_MARGIN + 3, sep_y, _MARGIN + _CONTENT_W, sep_y)

        # Detail rows
        label_w = _CONTENT_W * 0.4
        for i, (lbl, val) in enumerate(rows):
            ry = y0 + 17 + i * _ROW_H
            if i % 2 == 1:
                pdf.set_fill_color(238, 241, 245)
                pdf.rect(_MARGIN + 3, ry, _CONTENT_W - 3, _ROW_H, style="F")
            pdf.set_xy(_MARGIN + 6, ry)
            pdf.set_font(pdf._font_family, "", 7.5)
            pdf.set_text_color(*_TEXT_MUTED)
            pdf.cell(label_w, _ROW_H, lbl, ln=0)
            pdf.set_font(pdf._font_family, "B", 7.5)
            pdf.set_text_color(*_TEXT)
            pdf.cell(_CONTENT_W - label_w - 7, _ROW_H, val, ln=0)

        pdf.set_y(y0 + card_h + 6)

    pdf.set_text_color(*_TEXT)


def _config_page_body(
    pdf: MissionPDF, data: LastPlanData, operator: str, organization: str
) -> None:
    """Flight parameters, integrity hash, status."""
    pdf.header_bar("CONFIGURATION & INTEGRITY")
    fc = data.fc

    cfg_fields = [
        ("Min AGL", f"{fc.min_agl_m} m"),
        ("Max AGL", f"{fc.max_agl_m} m"),
        ("Safety radius", f"{fc.point_radius_m} m"),
        ("Camera range radius", f"{fc.max_surface_radius_m} m"),
        ("Cruise speed", f"{fc.cruise_speed_ms} m/s"),
        ("Climb rate", f"{fc.climb_rate_ms} m/s"),
        ("Route spacing", f"{fc.spacing_m} m"),
        ("Optimize POI order", "Yes" if fc.optimize_poi_order else "No"),
        ("Smart Route", "Yes" if fc.smart_route else "No"),
        ("Min altitude step", f"{fc.min_altitude_step_m} m"),
    ]
    if fc.max_slope_ratio is not None:
        cfg_fields.append(("Max slope ratio", f"1:{1 / fc.max_slope_ratio:.0f}"))
    if fc.smart_route:
        cfg_fields.append(("Smart Route corridor", f"{fc.smart_route_corridor_m} m"))

    pdf.section_title("Flight Parameters")
    _draw_two_col_table(pdf, cfg_fields)

    gen_utc = data.generated_at.replace("T", " ") + " UTC"
    op_str = (operator or "\u2014") + (f" / {organization}" if organization else "")
    pdf.section_title("Route Integrity")
    pdf.integrity_block(
        [
            f"SHA-256 Route ID: {data.route_hash}",
            f"Generated:        {gen_utc}",
            f"Mission:          {data.mission_name or 'Untitled'}",
            f"Operator:         {op_str}",
        ]
    )

    pdf.section_title("Mission Status")
    pdf.status_stamp(data)


def _draw_two_col_table(pdf: MissionPDF, rows: list[tuple[str, str]]) -> None:
    """Render key/value rows in two side-by-side columns."""
    half = math.ceil(len(rows) / 2)
    left = rows[:half]
    right = rows[half:]
    col_w = (_CONTENT_W - 4) / 2
    label_w = col_w * 0.55

    def draw_col(items: list[tuple[str, str]], x_off: float) -> float:
        for i, (lbl, val) in enumerate(items):
            y = pdf.get_y()
            if i % 2 == 1:
                pdf.set_fill_color(*_BG_SURFACE)
                pdf.rect(_MARGIN + x_off, y, col_w, _ROW_H, style="F")
            pdf.set_xy(_MARGIN + x_off + 4, y)
            pdf.set_font(pdf._font_family, "", 8)
            pdf.set_text_color(*_TEXT_MUTED)
            pdf.cell(label_w, _ROW_H, lbl, ln=0)
            pdf.set_font(pdf._font_family, "B", 8)
            pdf.set_text_color(*_TEXT)
            pdf.cell(col_w - label_w - 4, _ROW_H, val, ln=1)
        return pdf.get_y()

    y_start = pdf.get_y()
    y_left_end = draw_col(left, 0)
    pdf.set_y(y_start)
    y_right_end = draw_col(right, col_w + 4)
    pdf.set_y(max(y_left_end, y_right_end) + 2)
    pdf.set_text_color(*_TEXT)


# ── Two-pass generator ────────────────────────────────────────────────────────


def _build_pdf(
    data: LastPlanData,
    operator: str,
    organization: str,
    route_img: str,
    agl_img: str,
    profile_img: str,
    terrain_img: str | None,
    include_toc: bool,
    toc_map: dict[str, int] | None,
) -> tuple[MissionPDF, dict[str, int]]:
    """Build full PDF. Returns (pdf, page_map).

    page_map records the page each named section starts on (only populated
    when include_toc=False).
    """
    pdf = MissionPDF()
    pdf.mission_name = data.mission_name or "FlyHigh Mission"
    page_map: dict[str, int] = {}

    # Cover (page 1)
    pdf.add_page()
    _cover_page_body(pdf, data, operator, organization)

    # TOC (page 2) — only on second pass
    if include_toc and toc_map:
        _toc_page(pdf, toc_map)

    # Route overview
    pdf.add_page()
    page_map["Route Overview"] = pdf.page_no()
    _route_page_body(pdf, data, route_img)

    # Mission summary
    pdf.add_page()
    page_map["Mission Summary"] = pdf.page_no()
    _summary_page_body(pdf, data)

    # Safety analysis
    pdf.add_page()
    page_map["Safety Analysis"] = pdf.page_no()
    _safety_page_body(pdf, data, agl_img, terrain_img)

    # Altitude profile
    pdf.add_page()
    page_map["Altitude Profile"] = pdf.page_no()
    _profile_page_body(pdf, data, profile_img)

    # POI details (only if there are POIs)
    if data.pois:
        pdf.add_page()
        page_map["POI Details"] = pdf.page_no()
        _poi_page_body(pdf, data)

    # Config & integrity
    pdf.add_page()
    page_map["Config & Integrity"] = pdf.page_no()
    _config_page_body(pdf, data, operator, organization)

    return pdf, page_map


# ── Public API ────────────────────────────────────────────────────────────────


def generate_pdf(data: LastPlanData, operator_name: str, organization: str) -> bytes:
    """Generate the full mission report PDF and return as bytes."""
    landing_dist: float | None = None
    if 0 <= data.landing_index < len(data.cum_dists):
        landing_dist = float(data.cum_dists[data.landing_index])

    # Generate all charts once (base64 strings)
    route_img = route_overview_png(
        data.lats,
        data.lons,
        data.agl_arr,
        data.fc.min_agl_m,
        data.poi_indices,
        data.waypoint_indices,
        data.start_index,
        data.landing_index,
        data.fc.point_radius_m,
    )
    agl_img = agl_heatmap_png(data.lats, data.lons, data.agl_arr, data.fc.min_agl_m)
    profile_img = altitude_profile_png(
        data.cum_dists,
        data.final_alts,
        data.terrain_elevs,
        data.fc.min_agl_m,
        data.fc.max_agl_m,
        data.poi_distances,
        landing_dist,
    )
    terrain_img: str | None = None
    if (
        data.terrain_grid is not None
        and data.terrain_grid_lons is not None
        and data.terrain_grid_lats is not None
    ):
        terrain_img = terrain_map_png(
            data.terrain_grid,
            data.terrain_grid_lons,
            data.terrain_grid_lats,
            data.lats,
            data.lons,
            data.poi_indices,
            data.start_index,
            data.landing_index,
        )

    chart_args = (data, operator_name, organization, route_img, agl_img, profile_img, terrain_img)

    # Pass 1: no TOC — capture section page numbers
    _, page_map = _build_pdf(*chart_args, include_toc=False, toc_map=None)

    # Shift all page numbers by +1 (TOC page will be inserted as page 2)
    toc_map = {name: num + 1 for name, num in page_map.items()}

    # Pass 2: include TOC with correct page numbers
    pdf2, _ = _build_pdf(*chart_args, include_toc=True, toc_map=toc_map)

    return bytes(pdf2.output())
